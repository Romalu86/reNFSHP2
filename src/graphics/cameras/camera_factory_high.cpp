#include "camera_factory_support.hpp"
namespace nfs::game::world::camera {

void create_high_camera(void *director) {
    float high_arm_length = 6.30000019073486328125f;
    float high_arm_height = 1.5f;
    float high_yaw_back_tension = 0.20000000298023223876953125f;
    float high_yaw_out_tension = 0.5f;
    float high_pitch_back_tension = 0.25f;
    float high_pitch_out_tension = 1.5f;
    float high_pitch = 0.026000000536441802978515625f;
    float high_acceleration_spring = 3.0f;
    float high_acceleration_damper = 2.0f;
    float high_deceleration_spring = 20.0f;
    float high_deceleration_damper = 12.0f;
    float high_field_of_view = 71.5f;
    float high_rotation_tension = 4.0f;
    float high_2plr_arm_length = 6.30000019073486328125f;
    float high_2plr_arm_height = 1.5f;
    float high_2plr_yaw_back_tension = 0.20000000298023223876953125f;
    float high_2plr_yaw_out_tension = 0.5f;
    float high_2plr_pitch_back_tension = 0.25f;
    float high_2plr_pitch_out_tension = 1.5f;
    float high_2plr_pitch = 0.026000000536441802978515625f;
    float high_2plr_acceleration_spring = 3.0f;
    float high_2plr_acceleration_damper = 2.0f;
    float high_2plr_deceleration_spring = 20.0f;
    float high_2plr_deceleration_damper = 12.0f;
    float high_2plr_field_of_view = 71.5f;
    float high_2plr_rotation_tension = 4.0f;
    float high_2ptb_arm_length = 6.30000019073486328125f;
    float high_2ptb_arm_height = 1.5f;
    float high_2ptb_yaw_back_tension = 0.20000000298023223876953125f;
    float high_2ptb_yaw_out_tension = 0.5f;
    float high_2ptb_pitch_back_tension = 0.25f;
    float high_2ptb_pitch_out_tension = 1.5f;
    float high_2ptb_pitch = 0.026000000536441802978515625f;
    float high_2ptb_acceleration_spring = 3.0f;
    float high_2ptb_acceleration_damper = 2.0f;
    float high_2ptb_deceleration_spring = 20.0f;
    float high_2ptb_deceleration_damper = 12.0f;
    float high_2ptb_field_of_view = 71.5f;
    float high_2ptb_rotation_tension = 4.0f;
    read_camera_configuration([&](ini::Reader *reader) {
        ini::get_float(reader, "high", "ArmLength", &high_arm_length);
        ini::get_float(reader, "high", "ArmHeight", &high_arm_height);
        ini::get_float(reader, "high", "YawBackTension", &high_yaw_back_tension);
        ini::get_float(reader, "high", "YawOutTension", &high_yaw_out_tension);
        ini::get_float(reader, "high", "PitchBackTension", &high_pitch_back_tension);
        ini::get_float(reader, "high", "PitchOutTension", &high_pitch_out_tension);
        ini::get_float(reader, "high", "Pitch", &high_pitch);
        ini::get_float(reader, "high", "AccSpring", &high_acceleration_spring);
        ini::get_float(reader, "high", "AccDamper", &high_acceleration_damper);
        ini::get_float(reader, "high", "DeAccSpring", &high_deceleration_spring);
        ini::get_float(reader, "high", "DeAccDamper", &high_deceleration_damper);
        ini::get_float(reader, "high", "FOV", &high_field_of_view);
        ini::get_float(reader, "high", "RotationTension", &high_rotation_tension);
        ini::get_float(reader, "high-2plr", "ArmLength", &high_2plr_arm_length);
        ini::get_float(reader, "high-2plr", "ArmHeight", &high_2plr_arm_height);
        ini::get_float(reader, "high-2plr", "YawBackTension", &high_2plr_yaw_back_tension);
        ini::get_float(reader, "high-2plr", "YawOutTension", &high_2plr_yaw_out_tension);
        ini::get_float(reader, "high-2plr", "PitchBackTension", &high_2plr_pitch_back_tension);
        ini::get_float(reader, "high-2plr", "PitchOutTension", &high_2plr_pitch_out_tension);
        ini::get_float(reader, "high-2plr", "Pitch", &high_2plr_pitch);
        ini::get_float(reader, "high-2plr", "AccSpring", &high_2plr_acceleration_spring);
        ini::get_float(reader, "high-2plr", "AccDamper", &high_2plr_acceleration_damper);
        ini::get_float(reader, "high-2plr", "DeAccSpring", &high_2plr_deceleration_spring);
        ini::get_float(reader, "high-2plr", "DeAccDamper", &high_2plr_deceleration_damper);
        ini::get_float(reader, "high-2plr", "FOV", &high_2plr_field_of_view);
        ini::get_float(reader, "high-2plr", "RotationTension", &high_2plr_rotation_tension);
        ini::get_float(reader, "high-2ptb", "ArmLength", &high_2ptb_arm_length);
        ini::get_float(reader, "high-2ptb", "ArmHeight", &high_2ptb_arm_height);
        ini::get_float(reader, "high-2ptb", "YawBackTension", &high_2ptb_yaw_back_tension);
        ini::get_float(reader, "high-2ptb", "YawOutTension", &high_2ptb_yaw_out_tension);
        ini::get_float(reader, "high-2ptb", "PitchBackTension", &high_2ptb_pitch_back_tension);
        ini::get_float(reader, "high-2ptb", "PitchOutTension", &high_2ptb_pitch_out_tension);
        ini::get_float(reader, "high-2ptb", "Pitch", &high_2ptb_pitch);
        ini::get_float(reader, "high-2ptb", "AccSpring", &high_2ptb_acceleration_spring);
        ini::get_float(reader, "high-2ptb", "AccDamper", &high_2ptb_acceleration_damper);
        ini::get_float(reader, "high-2ptb", "DeAccSpring", &high_2ptb_deceleration_spring);
        ini::get_float(reader, "high-2ptb", "DeAccDamper", &high_2ptb_deceleration_damper);
        ini::get_float(reader, "high-2ptb", "FOV", &high_2ptb_field_of_view);
        ini::get_float(reader, "high-2ptb", "RotationTension", &high_2ptb_rotation_tension);
    });
    void *controller = allocate_controller(director, 1);
    void *position =
        allocate_behavior(496, "behavior - position follow car", construct_follow_position);
    at<float>(position, 104) = high_arm_length;
    at<float>(position, 100) = high_arm_height;
    at<float>(position, 112) = high_yaw_back_tension;
    at<float>(position, 108) = high_yaw_out_tension;
    at<float>(position, 120) = high_pitch_back_tension;
    at<float>(position, 116) = high_pitch_out_tension;
    at<float>(position, 124) = high_acceleration_spring;
    at<float>(position, 128) = high_acceleration_damper;
    at<float>(position, 132) = high_deceleration_spring;
    at<float>(position, 136) = high_deceleration_damper;
    save_full_follow_parameters(position);
    at<float>(position, 104) = high_2plr_arm_length;
    at<float>(position, 100) = high_2plr_arm_height;
    at<float>(position, 112) = high_2plr_yaw_back_tension;
    at<float>(position, 108) = high_2plr_yaw_out_tension;
    at<float>(position, 120) = high_2plr_pitch_back_tension;
    at<float>(position, 116) = high_2plr_pitch_out_tension;
    at<float>(position, 124) = high_2plr_acceleration_spring;
    at<float>(position, 128) = high_2plr_acceleration_damper;
    at<float>(position, 132) = high_2plr_deceleration_spring;
    at<float>(position, 136) = high_2plr_deceleration_damper;
    save_vertical_follow_parameters(position);
    at<float>(position, 104) = high_2ptb_arm_length;
    at<float>(position, 100) = high_2ptb_arm_height;
    at<float>(position, 112) = high_2ptb_yaw_back_tension;
    at<float>(position, 108) = high_2ptb_yaw_out_tension;
    at<float>(position, 120) = high_2ptb_pitch_back_tension;
    at<float>(position, 116) = high_2ptb_pitch_out_tension;
    at<float>(position, 124) = high_2ptb_acceleration_spring;
    at<float>(position, 128) = high_2ptb_acceleration_damper;
    at<float>(position, 132) = high_2ptb_deceleration_spring;
    at<float>(position, 136) = high_2ptb_deceleration_damper;
    save_horizontal_follow_parameters(position);
    at<void *>(controller, 80) = position;
    void *look = allocate_behavior(136, "behavior - look at follow car", construct_follow_look);
    at<float>(look, 8) = high_pitch;
    save_full_pitch(look);
    at<float>(look, 8) = high_2plr_pitch;
    save_vertical_pitch(look);
    at<float>(look, 8) = high_2ptb_pitch;
    save_horizontal_pitch(look);
    at<void *>(controller, 84) = look;
    at<float>(controller, 36) = high_field_of_view;
    save_full_interval(offset(controller, 4));
    at<float>(controller, 36) = high_2plr_field_of_view;
    save_vertical_interval(offset(controller, 4));
    at<float>(controller, 36) = high_2ptb_field_of_view;
    save_horizontal_interval(offset(controller, 4));
    void *fov = allocate_behavior(140, "behavior - FOV follow player car", construct_follow_fov);
    at<float>(fov, 4) = high_field_of_view;
    save_full_fov(fov);
    at<float>(fov, 4) = high_2plr_field_of_view;
    save_vertical_fov(fov);
    at<float>(fov, 4) = high_2ptb_field_of_view;
    save_horizontal_fov(fov);
    at<float>(fov, 28) = high_field_of_view;
    at<void *>(controller, 88) = fov;
    void *up =
        allocate_behavior(40, "behavior - up vector follow player car", construct_follow_up);
    at<Dword>(up, 8) = at<Dword>(up, 16) = 0;
    at<float>(up, 12) = 1;
    at<float>(up, 24) = high_rotation_tension;
    save_full_up_tension(up);
    at<float>(up, 24) = high_2plr_rotation_tension;
    save_vertical_up_tension(up);
    at<float>(up, 24) = high_2ptb_rotation_tension;
    save_horizontal_up_tension(up);
    at<void *>(controller, 96) = up;
    append_camera_mode(director, controller);
}
} // namespace nfs::game::world::camera
