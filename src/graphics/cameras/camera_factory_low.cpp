#include "camera_factory_support.hpp"
namespace nfs::game::world::camera {

void create_low_camera(void *director) {
    float low_arm_length = 5.099999904632568359375f;
    float low_arm_height = 1.5f;
    float low_yaw_back_tension = 0.20000000298023223876953125f;
    float low_yaw_out_tension = 0.5f;
    float low_pitch_back_tension = 0.25f;
    float low_pitch_out_tension = 1.5f;
    float low_pitch = 0.026000000536441802978515625f;
    float low_acceleration_spring = 3.0f;
    float low_acceleration_damper = 2.0f;
    float low_deceleration_spring = 20.0f;
    float low_deceleration_damper = 12.0f;
    float low_field_of_view = 71.5f;
    float low_rotation_tension = 4.0f;
    float low_2plr_arm_length = 5.099999904632568359375f;
    float low_2plr_arm_height = 1.5f;
    float low_2plr_yaw_back_tension = 0.20000000298023223876953125f;
    float low_2plr_yaw_out_tension = 0.5f;
    float low_2plr_pitch_back_tension = 0.25f;
    float low_2plr_pitch_out_tension = 1.5f;
    float low_2plr_pitch = 0.026000000536441802978515625f;
    float low_2plr_acceleration_spring = 3.0f;
    float low_2plr_acceleration_damper = 2.0f;
    float low_2plr_deceleration_spring = 20.0f;
    float low_2plr_deceleration_damper = 12.0f;
    float low_2plr_field_of_view = 71.5f;
    float low_2plr_rotation_tension = 4.0f;
    float low_2ptb_arm_length = 5.099999904632568359375f;
    float low_2ptb_arm_height = 1.5f;
    float low_2ptb_yaw_back_tension = 0.20000000298023223876953125f;
    float low_2ptb_yaw_out_tension = 0.5f;
    float low_2ptb_pitch_back_tension = 0.25f;
    float low_2ptb_pitch_out_tension = 1.5f;
    float low_2ptb_pitch = 0.026000000536441802978515625f;
    float low_2ptb_acceleration_spring = 3.0f;
    float low_2ptb_acceleration_damper = 2.0f;
    float low_2ptb_deceleration_spring = 20.0f;
    float low_2ptb_deceleration_damper = 12.0f;
    float low_2ptb_field_of_view = 71.5f;
    float low_2ptb_rotation_tension = 4.0f;
    read_camera_configuration([&](ini::Reader *reader) {
        ini::get_float(reader, "low", "ArmLength", &low_arm_length);
        ini::get_float(reader, "low", "ArmHeight", &low_arm_height);
        ini::get_float(reader, "low", "YawBackTension", &low_yaw_back_tension);
        ini::get_float(reader, "low", "YawOutTension", &low_yaw_out_tension);
        ini::get_float(reader, "low", "PitchBackTension", &low_pitch_back_tension);
        ini::get_float(reader, "low", "PitchOutTension", &low_pitch_out_tension);
        ini::get_float(reader, "low", "Pitch", &low_pitch);
        ini::get_float(reader, "low", "AccSpring", &low_acceleration_spring);
        ini::get_float(reader, "low", "AccDamper", &low_acceleration_damper);
        ini::get_float(reader, "low", "DeAccSpring", &low_deceleration_spring);
        ini::get_float(reader, "low", "DeAccDamper", &low_deceleration_damper);
        ini::get_float(reader, "low", "FOV", &low_field_of_view);
        ini::get_float(reader, "low", "RotationTension", &low_rotation_tension);
        ini::get_float(reader, "low-2plr", "ArmLength", &low_2plr_arm_length);
        ini::get_float(reader, "low-2plr", "ArmHeight", &low_2plr_arm_height);
        ini::get_float(reader, "low-2plr", "YawBackTension", &low_2plr_yaw_back_tension);
        ini::get_float(reader, "low-2plr", "YawOutTension", &low_2plr_yaw_out_tension);
        ini::get_float(reader, "low-2plr", "PitchBackTension", &low_2plr_pitch_back_tension);
        ini::get_float(reader, "low-2plr", "PitchOutTension", &low_2plr_pitch_out_tension);
        ini::get_float(reader, "low-2plr", "Pitch", &low_2plr_pitch);
        ini::get_float(reader, "low-2plr", "AccSpring", &low_2plr_acceleration_spring);
        ini::get_float(reader, "low-2plr", "AccDamper", &low_2plr_acceleration_damper);
        ini::get_float(reader, "low-2plr", "DeAccSpring", &low_2plr_deceleration_spring);
        ini::get_float(reader, "low-2plr", "DeAccDamper", &low_2plr_deceleration_damper);
        ini::get_float(reader, "low-2plr", "FOV", &low_2plr_field_of_view);
        ini::get_float(reader, "low-2plr", "RotationTension", &low_2plr_rotation_tension);
        ini::get_float(reader, "low-2ptb", "ArmLength", &low_2ptb_arm_length);
        ini::get_float(reader, "low-2ptb", "ArmHeight", &low_2ptb_arm_height);
        ini::get_float(reader, "low-2ptb", "YawBackTension", &low_2ptb_yaw_back_tension);
        ini::get_float(reader, "low-2ptb", "YawOutTension", &low_2ptb_yaw_out_tension);
        ini::get_float(reader, "low-2ptb", "PitchBackTension", &low_2ptb_pitch_back_tension);
        ini::get_float(reader, "low-2ptb", "PitchOutTension", &low_2ptb_pitch_out_tension);
        ini::get_float(reader, "low-2ptb", "Pitch", &low_2ptb_pitch);
        ini::get_float(reader, "low-2ptb", "AccSpring", &low_2ptb_acceleration_spring);
        ini::get_float(reader, "low-2ptb", "AccDamper", &low_2ptb_acceleration_damper);
        ini::get_float(reader, "low-2ptb", "DeAccSpring", &low_2ptb_deceleration_spring);
        ini::get_float(reader, "low-2ptb", "DeAccDamper", &low_2ptb_deceleration_damper);
        ini::get_float(reader, "low-2ptb", "FOV", &low_2ptb_field_of_view);
        ini::get_float(reader, "low-2ptb", "RotationTension", &low_2ptb_rotation_tension);
    });
    void *controller = allocate_controller(director, 0);
    void *position =
        allocate_behavior(496, "behavior - position follow car", construct_follow_position);
    at<float>(position, 104) = low_arm_length;
    at<float>(position, 100) = low_arm_height;
    at<float>(position, 112) = low_yaw_back_tension;
    at<float>(position, 108) = low_yaw_out_tension;
    at<float>(position, 120) = low_pitch_back_tension;
    at<float>(position, 116) = low_pitch_out_tension;
    at<float>(position, 124) = low_acceleration_spring;
    at<float>(position, 128) = low_acceleration_damper;
    at<float>(position, 132) = low_deceleration_spring;
    at<float>(position, 136) = low_deceleration_damper;
    save_full_follow_parameters(position);
    at<float>(position, 104) = low_2plr_arm_length;
    at<float>(position, 100) = low_2plr_arm_height;
    at<float>(position, 112) = low_2plr_yaw_back_tension;
    at<float>(position, 108) = low_2plr_yaw_out_tension;
    at<float>(position, 120) = low_2plr_pitch_back_tension;
    at<float>(position, 116) = low_2plr_pitch_out_tension;
    at<float>(position, 124) = low_2plr_acceleration_spring;
    at<float>(position, 128) = low_2plr_acceleration_damper;
    at<float>(position, 132) = low_2plr_deceleration_spring;
    at<float>(position, 136) = low_2plr_deceleration_damper;
    save_vertical_follow_parameters(position);
    at<float>(position, 104) = low_2ptb_arm_length;
    at<float>(position, 100) = low_2ptb_arm_height;
    at<float>(position, 112) = low_2ptb_yaw_back_tension;
    at<float>(position, 108) = low_2ptb_yaw_out_tension;
    at<float>(position, 120) = low_2ptb_pitch_back_tension;
    at<float>(position, 116) = low_2ptb_pitch_out_tension;
    at<float>(position, 124) = low_2ptb_acceleration_spring;
    at<float>(position, 128) = low_2ptb_acceleration_damper;
    at<float>(position, 132) = low_2ptb_deceleration_spring;
    at<float>(position, 136) = low_2ptb_deceleration_damper;
    save_horizontal_follow_parameters(position);
    at<void *>(controller, 80) = position;
    void *look = allocate_behavior(136, "behavior - look at follow car", construct_follow_look);
    at<float>(look, 8) = low_pitch;
    save_full_pitch(look);
    at<float>(look, 8) = low_2plr_pitch;
    save_vertical_pitch(look);
    at<float>(look, 8) = low_2ptb_pitch;
    save_horizontal_pitch(look);
    at<void *>(controller, 84) = look;
    at<float>(controller, 36) = low_field_of_view;
    save_full_interval(offset(controller, 4));
    at<float>(controller, 36) = low_2plr_field_of_view;
    save_vertical_interval(offset(controller, 4));
    at<float>(controller, 36) = low_2ptb_field_of_view;
    save_horizontal_interval(offset(controller, 4));
    void *fov = allocate_behavior(140, "behavior - FOV follow player car", construct_follow_fov);
    at<float>(fov, 4) = low_field_of_view;
    save_full_fov(fov);
    at<float>(fov, 4) = low_2plr_field_of_view;
    save_vertical_fov(fov);
    at<float>(fov, 4) = low_2ptb_field_of_view;
    save_horizontal_fov(fov);
    at<float>(fov, 28) = low_field_of_view;
    at<void *>(controller, 88) = fov;
    void *up =
        allocate_behavior(40, "behavior - up vector follow player car", construct_follow_up);
    at<Dword>(up, 8) = at<Dword>(up, 16) = 0;
    at<float>(up, 12) = 1;
    at<float>(up, 24) = low_rotation_tension;
    save_full_up_tension(up);
    at<float>(up, 24) = low_2plr_rotation_tension;
    save_vertical_up_tension(up);
    at<float>(up, 24) = low_2ptb_rotation_tension;
    save_horizontal_up_tension(up);
    at<void *>(controller, 96) = up;
    append_camera_mode(director, controller);
}
} // namespace nfs::game::world::camera
