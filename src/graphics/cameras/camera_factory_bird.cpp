#include "camera_factory_support.hpp"
namespace nfs::game::world::camera {

void create_bird_camera(void *director) {
    float bird_arm_length = 17.0f;
    float bird_arm_height = 3.75f;
    float bird_yaw_back_tension = 0.20000000298023223876953125f;
    float bird_yaw_out_tension = 0.5f;
    float bird_pitch_back_tension = 0.25f;
    float bird_pitch_out_tension = 1.5f;
    float bird_pitch = 1.00899994373321533203125f;
    float bird_field_of_view = 55.0f;
    float bird_rotation_tension = 4.0f;
    float bird_2plr_arm_length = 17.0f;
    float bird_2plr_arm_height = 3.75f;
    float bird_2plr_yaw_back_tension = 0.20000000298023223876953125f;
    float bird_2plr_yaw_out_tension = 0.5f;
    float bird_2plr_pitch_back_tension = 0.25f;
    float bird_2plr_pitch_out_tension = 1.5f;
    float bird_2plr_pitch = 1.00899994373321533203125f;
    float bird_2plr_field_of_view = 55.0f;
    float bird_2plr_rotation_tension = 4.0f;
    float bird_2ptb_arm_length = 17.0f;
    float bird_2ptb_arm_height = 3.75f;
    float bird_2ptb_yaw_back_tension = 0.20000000298023223876953125f;
    float bird_2ptb_yaw_out_tension = 0.5f;
    float bird_2ptb_pitch_back_tension = 0.25f;
    float bird_2ptb_pitch_out_tension = 1.5f;
    float bird_2ptb_pitch = 1.00899994373321533203125f;
    float bird_2ptb_field_of_view = 55.0f;
    float bird_2ptb_rotation_tension = 4.0f;
    read_camera_configuration([&](ini::Reader *reader) {
        ini::get_float(reader, "bird", "ArmLength", &bird_arm_length);
        ini::get_float(reader, "bird", "ArmHeight", &bird_arm_height);
        ini::get_float(reader, "bird", "YawBackTension", &bird_yaw_back_tension);
        ini::get_float(reader, "bird", "YawOutTension", &bird_yaw_out_tension);
        ini::get_float(reader, "bird", "PitchBackTension", &bird_pitch_back_tension);
        ini::get_float(reader, "bird", "PitchOutTension", &bird_pitch_out_tension);
        ini::get_float(reader, "bird", "Pitch", &bird_pitch);
        ini::get_float(reader, "bird", "FOV", &bird_field_of_view);
        ini::get_float(reader, "bird", "RotationTension", &bird_rotation_tension);
        ini::get_float(reader, "bird-2plr", "ArmLength", &bird_2plr_arm_length);
        ini::get_float(reader, "bird-2plr", "ArmHeight", &bird_2plr_arm_height);
        ini::get_float(reader, "bird-2plr", "YawBackTension", &bird_2plr_yaw_back_tension);
        ini::get_float(reader, "bird-2plr", "YawOutTension", &bird_2plr_yaw_out_tension);
        ini::get_float(reader, "bird-2plr", "PitchBackTension", &bird_2plr_pitch_back_tension);
        ini::get_float(reader, "bird-2plr", "PitchOutTension", &bird_2plr_pitch_out_tension);
        ini::get_float(reader, "bird-2plr", "Pitch", &bird_2plr_pitch);
        ini::get_float(reader, "bird-2plr", "FOV", &bird_2plr_field_of_view);
        ini::get_float(reader, "bird-2plr", "RotationTension", &bird_2plr_rotation_tension);
        ini::get_float(reader, "bird-2ptb", "ArmLength", &bird_2ptb_arm_length);
        ini::get_float(reader, "bird-2ptb", "ArmHeight", &bird_2ptb_arm_height);
        ini::get_float(reader, "bird-2ptb", "YawBackTension", &bird_2ptb_yaw_back_tension);
        ini::get_float(reader, "bird-2ptb", "YawOutTension", &bird_2ptb_yaw_out_tension);
        ini::get_float(reader, "bird-2ptb", "PitchBackTension", &bird_2ptb_pitch_back_tension);
        ini::get_float(reader, "bird-2ptb", "PitchOutTension", &bird_2ptb_pitch_out_tension);
        ini::get_float(reader, "bird-2ptb", "Pitch", &bird_2ptb_pitch);
        ini::get_float(reader, "bird-2ptb", "FOV", &bird_2ptb_field_of_view);
        ini::get_float(reader, "bird-2ptb", "RotationTension", &bird_2ptb_rotation_tension);
    });
    void *controller = allocate_controller(director, 2);
    void *position =
        allocate_behavior(496, "behavior - position follow car", construct_follow_position);
    at<float>(position, 104) = bird_arm_length;
    at<float>(position, 100) = bird_arm_height;
    at<float>(position, 112) = bird_yaw_back_tension;
    at<float>(position, 108) = bird_yaw_out_tension;
    at<float>(position, 120) = bird_pitch_back_tension;
    at<float>(position, 116) = bird_pitch_out_tension;
    save_full_follow_parameters(position);
    at<float>(position, 104) = bird_2plr_arm_length;
    at<float>(position, 100) = bird_2plr_arm_height;
    at<float>(position, 112) = bird_2plr_yaw_back_tension;
    at<float>(position, 108) = bird_2plr_yaw_out_tension;
    at<float>(position, 120) = bird_2plr_pitch_back_tension;
    at<float>(position, 116) = bird_2plr_pitch_out_tension;
    save_vertical_follow_parameters(position);
    at<float>(position, 104) = bird_2ptb_arm_length;
    at<float>(position, 100) = bird_2ptb_arm_height;
    at<float>(position, 112) = bird_2ptb_yaw_back_tension;
    at<float>(position, 108) = bird_2ptb_yaw_out_tension;
    at<float>(position, 120) = bird_2ptb_pitch_back_tension;
    at<float>(position, 116) = bird_2ptb_pitch_out_tension;
    save_horizontal_follow_parameters(position);
    at<Byte>(position, 97) = 0;
    at<void *>(controller, 80) = position;
    void *look = allocate_behavior(136, "behavior - look at follow car", construct_follow_look);
    at<float>(look, 8) = bird_pitch;
    save_full_pitch(look);
    at<float>(look, 8) = bird_2plr_pitch;
    save_vertical_pitch(look);
    at<float>(look, 8) = bird_2ptb_pitch;
    save_horizontal_pitch(look);
    at<void *>(controller, 84) = look;
    at<float>(controller, 36) = bird_field_of_view;
    save_full_interval(offset(controller, 4));
    at<float>(controller, 36) = bird_2plr_field_of_view;
    save_vertical_interval(offset(controller, 4));
    at<float>(controller, 36) = bird_2ptb_field_of_view;
    save_horizontal_interval(offset(controller, 4));
    void *fov = allocate_behavior(140, "behavior - FOV follow player car", construct_follow_fov);
    at<float>(fov, 4) = bird_field_of_view;
    save_full_fov(fov);
    at<float>(fov, 4) = bird_2plr_field_of_view;
    save_vertical_fov(fov);
    at<float>(fov, 4) = bird_2ptb_field_of_view;
    save_horizontal_fov(fov);
    at<float>(fov, 28) = bird_field_of_view;
    at<void *>(controller, 88) = fov;
    void *up =
        allocate_behavior(40, "behavior - up vector follow player car", construct_follow_up);
    at<Dword>(up, 8) = at<Dword>(up, 16) = 0;
    at<float>(up, 12) = 1;
    at<float>(up, 24) = bird_rotation_tension;
    save_full_up_tension(up);
    at<float>(up, 24) = bird_2plr_rotation_tension;
    save_vertical_up_tension(up);
    at<float>(up, 24) = bird_2ptb_rotation_tension;
    save_horizontal_up_tension(up);
    at<void *>(controller, 96) = up;
    append_camera_mode(director, controller);
}
} // namespace nfs::game::world::camera
