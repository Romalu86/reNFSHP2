inline void *interface_at(void *entity, unsigned slot, unsigned base = 4) {
    return bytes(entity) + base + at<const int *>(entity, base)[slot];
}
inline void *adjust_interface(void *view) {
    const int adjustment = *reinterpret_cast<const volatile int *>(bytes(view) - 4);
    return bytes(view) - adjustment;
}
